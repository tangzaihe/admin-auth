-- =============================================================================
-- admin-auth H2 demo schema（由 spring.sql.init 加载；MySQL 生产使用 V1/V2 迁移）
-- 转换规则（第 3 段）：去 ENGINE/CHARSET/COMMENT/ON UPDATE/GENERATED；
--   active_hash 改普通 BINARY(32) NULL；DATETIME(3) → TIMESTAMP(3)；JSON → VARCHAR(4000)
-- =============================================================================

CREATE TABLE IF NOT EXISTS adm_user (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name         VARCHAR(64)  NOT NULL DEFAULT '',
  role                 VARCHAR(32)  NOT NULL DEFAULT 'ADMIN',
  status               TINYINT      NOT NULL DEFAULT 1,
  password_hash        VARCHAR(100) NOT NULL,
  password_algo        VARCHAR(16)  NOT NULL DEFAULT 'BCRYPT',
  must_change_password TINYINT      NOT NULL DEFAULT 1,
  mfa_state            TINYINT      NOT NULL DEFAULT 0,
  mfa_required         TINYINT      NOT NULL DEFAULT -1,
  token_version        INT          NOT NULL DEFAULT 0,
  pwd_updated_at       TIMESTAMP(3) NULL,
  last_login_at        TIMESTAMP(3) NULL,
  created_at           TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at           TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS adm_identity (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         BIGINT        NOT NULL,
  identity_type   VARCHAR(16)   NOT NULL,
  value_enc       VARBINARY(512) NOT NULL,
  key_version     SMALLINT      NOT NULL DEFAULT 1,
  value_hash      BINARY(32)    NOT NULL,
  value_mask      VARCHAR(64)   NOT NULL DEFAULT '',
  verified_at     TIMESTAMP(3)  NULL,
  consent_at      TIMESTAMP(3)  NULL,
  consent_version VARCHAR(16)   NOT NULL DEFAULT '',
  is_primary      TINYINT       NOT NULL DEFAULT 0,
  status          TINYINT       NOT NULL DEFAULT 1,
  active_hash     BINARY(32)    NULL,
  created_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_adm_identity_active UNIQUE (identity_type, active_hash)
);
CREATE INDEX IF NOT EXISTS idx_adm_identity_user ON adm_identity (user_id, identity_type);

CREATE TABLE IF NOT EXISTS adm_mfa_factor (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        BIGINT        NOT NULL,
  factor_type    VARCHAR(16)   NOT NULL,
  identity_id    BIGINT        NOT NULL DEFAULT 0,
  secret_enc     VARBINARY(512) NULL,
  key_version    SMALLINT      NOT NULL DEFAULT 1,
  digits         TINYINT       NOT NULL DEFAULT 6,
  period         SMALLINT      NOT NULL DEFAULT 30,
  last_used_step BIGINT        NOT NULL DEFAULT 0,
  payload        VARCHAR(4000) NULL,
  priority       SMALLINT      NOT NULL DEFAULT 100,
  confirmed_at   TIMESTAMP(3)  NULL,
  fail_count     INT           NOT NULL DEFAULT 0,
  locked_until   TIMESTAMP(3)  NULL,
  status         TINYINT       NOT NULL DEFAULT 1,
  created_at     TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_adm_factor_user_type UNIQUE (user_id, factor_type, identity_id)
);
CREATE INDEX IF NOT EXISTS idx_adm_factor_user ON adm_mfa_factor (user_id, status);

CREATE TABLE IF NOT EXISTS adm_otp_code (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT       NOT NULL,
  factor_type VARCHAR(16)  NOT NULL,
  identity_id BIGINT       NOT NULL,
  scene       VARCHAR(16)  NOT NULL,
  code_hash   BINARY(32)   NOT NULL,
  attempts    TINYINT      NOT NULL DEFAULT 0,
  status      VARCHAR(16)  NOT NULL DEFAULT 'ISSUED',
  expires_at  TIMESTAMP(3) NOT NULL,
  created_at  TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  verified_at TIMESTAMP(3) NULL
);
CREATE INDEX IF NOT EXISTS idx_adm_otp_user_scene ON adm_otp_code (user_id, scene, status);
CREATE INDEX IF NOT EXISTS idx_adm_otp_expire ON adm_otp_code (expires_at);

CREATE TABLE IF NOT EXISTS adm_recovery_code (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT        NOT NULL,
  code_hash  VARCHAR(100)  NOT NULL,
  used_at    TIMESTAMP(3)  NULL,
  created_at TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_adm_recovery_user ON adm_recovery_code (user_id);

CREATE TABLE IF NOT EXISTS adm_audit_log (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT       NULL,
  actor_user_id BIGINT       NULL,
  identity_type VARCHAR(16)  NOT NULL DEFAULT '',
  factor_type   VARCHAR(16)  NOT NULL DEFAULT '',
  channel_mask  VARCHAR(64)  NOT NULL DEFAULT '',
  event         VARCHAR(48)  NOT NULL,
  result        VARCHAR(16)  NOT NULL,
  ip            VARCHAR(45)  NOT NULL DEFAULT '',
  user_agent    VARCHAR(255) NOT NULL DEFAULT '',
  detail        VARCHAR(4000) NULL,
  created_at    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_adm_audit_user_time ON adm_audit_log (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_adm_audit_event_time ON adm_audit_log (event, created_at);

CREATE TABLE IF NOT EXISTS adm_login_attempt (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT      NULL,
  identity_hash BINARY(32)  NOT NULL,
  ip            VARCHAR(45) NOT NULL,
  fail_count    INT         NOT NULL DEFAULT 0,
  locked_until  TIMESTAMP(3) NULL,
  updated_at    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_adm_attempt UNIQUE (identity_hash, ip)
);
CREATE INDEX IF NOT EXISTS idx_adm_attempt_user ON adm_login_attempt (user_id, ip);

-- Spring Session JDBC（表名与 DDL 一致：ADM_SESSION / ADM_SESSION_ATTRIBUTES）
CREATE TABLE IF NOT EXISTS ADM_SESSION (
  PRIMARY_ID            CHAR(36) NOT NULL,
  SESSION_ID            CHAR(36) NOT NULL,
  CREATION_TIME         BIGINT   NOT NULL,
  LAST_ACCESS_TIME      BIGINT   NOT NULL,
  MAX_INACTIVE_INTERVAL INT      NOT NULL,
  EXPIRY_TIME           BIGINT   NOT NULL,
  PRINCIPAL_NAME        VARCHAR(100) NULL,
  CONSTRAINT ADM_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS ADM_SESSION_IX1 ON ADM_SESSION (SESSION_ID);
CREATE INDEX IF NOT EXISTS ADM_SESSION_IX2 ON ADM_SESSION (EXPIRY_TIME);
CREATE INDEX IF NOT EXISTS ADM_SESSION_IX3 ON ADM_SESSION (PRINCIPAL_NAME);

CREATE TABLE IF NOT EXISTS ADM_SESSION_ATTRIBUTES (
  SESSION_PRIMARY_ID CHAR(36)     NOT NULL,
  ATTRIBUTE_NAME     VARCHAR(200) NOT NULL,
  ATTRIBUTE_BYTES    BLOB         NOT NULL,
  CONSTRAINT ADM_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
  CONSTRAINT ADM_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
    REFERENCES ADM_SESSION (PRIMARY_ID) ON DELETE CASCADE
);
